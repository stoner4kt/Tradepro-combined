#!/usr/bin/env bash
set -euo pipefail

: "${SUPABASE_URL:?Set SUPABASE_URL to the target project URL}"
: "${SUPABASE_ANON_KEY:?Set SUPABASE_ANON_KEY to the project's anon key}"

base="${SUPABASE_URL%/}/functions/v1"
functions=(
  capture-lead
  integration-capture
  integration-lead
  integration-lookup
  integration-overview
  integration-send-review
  integration-settings
  invoicing-api
  invoicing-cron
  invoicing-public
  invoicing-resend-webhook
  reviewflow-unsubscribe
  send-review-email
)

failed=0
for name in "${functions[@]}"; do
  response_file="$(mktemp)"
  status="$(curl --silent --show-error --output "$response_file" --write-out '%{http_code}' \
    --header "apikey: $SUPABASE_ANON_KEY" \
    --header 'Accept: application/json' \
    "$base/$name" || true)"
  body="$(cat "$response_file")"
  rm -f "$response_file"

  if [[ "$status" == "401" ]] && grep -Eqi 'invalid jwt|missing authorization header|invalid authentication credentials' <<<"$body"; then
    echo "FAIL $name: Supabase JWT gateway rejected the no-JWT request ($status): $body" >&2
    failed=1
  elif [[ ! "$status" =~ ^[1-5][0-9][0-9]$ ]]; then
    echo "FAIL $name: unexpected HTTP status '$status'" >&2
    failed=1
  else
    echo "PASS $name: function reached (HTTP $status)"
  fi
done

if [[ "$failed" -ne 0 ]]; then
  echo "One or more functions appear to have verify_jwt enabled at the gateway." >&2
  exit 1
fi

echo "Smoke check complete. 401/403 responses generated by each function's own auth are expected."
